/**
 * Writes server/data/overture-places.ts: where the places of one Overture
 * Maps release sit in its Parquet files. For every row group, its row count
 * and the box its places fall in (from the bbox column statistics), rounded
 * outward to 0.001°. The street lookup reads only the row groups whose box
 * meets the street, so it never downloads a whole file.
 *
 *   node scripts/overture-index.mjs            # the newest release
 *   node scripts/overture-index.mjs 2026-10-21.0
 *
 * Reads the files' footers only (about 40 MB in all) from the public bucket.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { asyncBufferFromUrl, parquetMetadataAsync } from "hyparquet";

const BASE = "https://overturemaps-us-west-2.s3.amazonaws.com/";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function list(prefix, delimiter) {
  const url = `${BASE}?list-type=2&prefix=${encodeURIComponent(prefix)}${delimiter ? "&delimiter=/" : ""}`;
  const xml = await (await fetch(url)).text();
  return {
    prefixes: [...xml.matchAll(/<Prefix>([^<]*)<\/Prefix>/g)].map((m) => m[1]),
    objects: [...xml.matchAll(/<Contents>([\s\S]*?)<\/Contents>/g)].map((m) => ({
      key: /<Key>([^<]*)<\/Key>/.exec(m[1])[1],
      size: Number(/<Size>(\d+)<\/Size>/.exec(m[1])[1]),
    })),
  };
}

let release = process.argv[2];
if (!release) {
  const releases = (await list("release/", true)).prefixes.map((p) => p.split("/")[1]).filter((r) => /^\d{4}-\d{2}-\d{2}\.\d+$/.test(r));
  release = releases.sort().at(-1);
}
const files = (await list(`release/${release}/theme=places/type=place/`, false)).objects.filter((o) => o.key.endsWith(".parquet"));
if (files.length === 0) throw new Error(`No place files for release ${release}`);

const floor3 = (x) => Math.floor(x * 1000) / 1000;
const ceil3 = (x) => Math.ceil(x * 1000) / 1000;
const out = [];
for (const { key, size } of files) {
  const file = await asyncBufferFromUrl({ url: BASE + key, byteLength: size });
  const metadata = await parquetMetadataAsync(file);
  const groups = [];
  for (const group of metadata.row_groups) {
    const stat = (path, which) => {
      const chunk = group.columns.find((c) => c.meta_data?.path_in_schema.join(".") === path);
      const s = chunk?.meta_data?.statistics;
      const v = which === "min" ? (s?.min_value ?? s?.min) : (s?.max_value ?? s?.max);
      if (typeof v !== "number") throw new Error(`${key}: no ${which} for ${path}`);
      return v;
    };
    groups.push(Number(group.num_rows), floor3(stat("bbox.xmin", "min")), floor3(stat("bbox.ymin", "min")), ceil3(stat("bbox.xmax", "max")), ceil3(stat("bbox.ymax", "max")));
  }
  out.push({ key, size, groups });
  console.log(`${key.split("/").at(-1).slice(0, 10)}: ${metadata.row_groups.length} row groups`);
}

const body = out.map((f) => `    { key: ${JSON.stringify(f.key)}, size: ${f.size}, groups: [${f.groups.join(",")}] },`).join("\n");
writeFileSync(
  join(root, "server/data/overture-places.ts"),
  `/**
 * Generated by scripts/overture-index.mjs; do not edit by hand. The Overture
 * Maps places release ${release}: for each Parquet file its size and, for
 * each row group, five numbers: rows, west, south, east, north (degrees,
 * rounded outward to 0.001°).
 */
export type OverturePlacesIndex = { release: string; base: string; files: { key: string; size: number; groups: number[] }[] };

export const OVERTURE_PLACES: OverturePlacesIndex = {
  release: ${JSON.stringify(release)},
  base: ${JSON.stringify(BASE)},
  files: [
${body}
  ],
};
`,
);
console.log(`Wrote server/data/overture-places.ts for ${release}: ${files.length} files, ${out.reduce((n, f) => n + f.groups.length / 5, 0)} row groups.`);
